#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { PROVIDER_PRESETS } from '../out/services/providerPresets.js';

const GATEWAY_MODELS_URL = 'https://ai-gateway.vercel.sh/v1/models';
const OUTPUT_FILE = new URL('../src/usage/modelPricing.generated.ts', import.meta.url);
const FETCH_TIMEOUT_MS = 30_000;

function readNumberString(value) {
  if (typeof value !== 'string' || !value.trim()) return undefined;
  const parsed = Number(value);
  return Number.isFinite(parsed) && parsed >= 0 ? parsed : undefined;
}

function readPositiveInteger(value) {
  return Number.isInteger(value) && value > 0 ? value : undefined;
}

function collectRequiredGatewayModelIds() {
  const required = [];
  for (const preset of PROVIDER_PRESETS) {
    if (preset.id === 'openrouter' || preset.id === 'openaiCompatible') continue;
    for (const option of preset.modelOptions) {
      if (!option.modelId) continue;
      if (!option.gatewayModelId) {
        required.push({ provider: preset.id, modelId: option.modelId, gatewayModelId: undefined });
        continue;
      }
      required.push({ provider: preset.id, modelId: option.modelId, gatewayModelId: option.gatewayModelId });
    }
  }
  return required;
}

function toGeneratedSource(table) {
  return `// Generated by scripts/sync-model-pricing.mjs. Do not edit by hand.
export const MODEL_PRICING = ${JSON.stringify(table, null, 2)} as const;
`;
}

async function readExistingTable() {
  let source;
  try {
    source = await readFile(OUTPUT_FILE, 'utf8');
  } catch (error) {
    if (error && typeof error === 'object' && error.code === 'ENOENT') return undefined;
    throw error;
  }
  const match = source.match(/export const MODEL_PRICING = ([\s\S]+) as const;\s*$/);
  if (!match) {
    throw new Error(`Existing pricing snapshot has an unexpected format: ${OUTPUT_FILE.pathname}`);
  }
  const table = JSON.parse(match[1]);
  if (!table || typeof table !== 'object' || Array.isArray(table)) {
    throw new Error(`Existing pricing snapshot must contain an object: ${OUTPUT_FILE.pathname}`);
  }
  return table;
}

function comparableTable(table) {
  const { fetchedAt: _fetchedAt, ...comparable } = table;
  return comparable;
}

function tablesMatch(existing, next) {
  return JSON.stringify(comparableTable(existing)) === JSON.stringify(comparableTable(next));
}

async function main() {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), FETCH_TIMEOUT_MS);
  let response;
  try {
    response = await fetch(GATEWAY_MODELS_URL, { signal: controller.signal });
  } finally {
    clearTimeout(timeout);
  }
  if (!response.ok) {
    throw new Error(`Failed to fetch Gateway models: HTTP ${response.status}`);
  }
  const payload = await response.json();
  const data = Array.isArray(payload?.data) ? payload.data : undefined;
  if (!data) {
    throw new Error('Gateway models response did not contain a data array.');
  }

  const modelsById = new Map(data.map((model) => [model.id, model]));
  const required = collectRequiredGatewayModelIds();
  const missing = [];
  const models = {};

  for (const item of required) {
    if (!item.gatewayModelId) {
      missing.push(`${item.provider}:${item.modelId} is missing gatewayModelId`);
      continue;
    }
    const model = modelsById.get(item.gatewayModelId);
    if (!model) {
      missing.push(`${item.provider}:${item.modelId} -> ${item.gatewayModelId} was not found`);
      continue;
    }
    const input = readNumberString(model.pricing?.input);
    const output = readNumberString(model.pricing?.output);
    if (input === undefined || output === undefined) {
      missing.push(`${item.provider}:${item.modelId} -> ${item.gatewayModelId} is missing input/output pricing`);
      continue;
    }
    models[item.gatewayModelId] = {
      input,
      output,
      contextWindow: readPositiveInteger(model.context_window),
      maxTokens: readPositiveInteger(model.max_tokens),
    };
  }

  if (missing.length > 0) {
    throw new Error(`Gateway pricing coverage failed:\n${missing.map((item) => `- ${item}`).join('\n')}`);
  }

  const table = {
    schemaVersion: 1,
    source: 'vercel-ai-gateway',
    sourceUrl: GATEWAY_MODELS_URL,
    fetchedAt: new Date().toISOString(),
    currency: 'USD',
    unit: 'per_token',
    models,
  };

  const existingTable = await readExistingTable();
  if (existingTable && tablesMatch(existingTable, table)) {
    console.log(
      `Gateway pricing is unchanged for ${Object.keys(models).length} models; kept the existing snapshot.`,
    );
    return;
  }

  await writeFile(OUTPUT_FILE, toGeneratedSource(table), 'utf8');
  console.log(`Wrote ${Object.keys(models).length} model prices to ${OUTPUT_FILE.pathname}`);
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
